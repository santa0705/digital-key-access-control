"""
tests/unit/test_contract_paths.py

Automated Contract Path Drift Guard for Digital Key-Based Secure Access Control.
Verifies API contract paths and HTTP methods against FastAPI application routes.
Authoritative specification: docs/api-contract.md §2 (Path Drift Guard List) and §5 (Endpoints).
"""

from pathlib import Path
import re
from fastapi import FastAPI
from fastapi.routing import APIRoute
import pytest

from app.main import app

# Repository root resolved from test file location:
# tests/unit/test_contract_paths.py -> tests/unit -> tests -> repo root
REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CONTRACT_FILE = REPO_ROOT / "docs" / "api-contract.md"

# FastAPI built-in routes to exclude from application contract checks
FASTAPI_BUILTIN_PATHS = {
    "/docs",
    "/redoc",
    "/openapi.json",
    "/docs/oauth2-redirect",
}


def parse_contract_guard_paths(doc_path: Path = CONTRACT_FILE) -> list[str]:
    """
    Parses the authoritative 13 paths directly from Section 2 of docs/api-contract.md.
    Extracts lines from the fenced code block under '## 2. Path Drift Guard List'.
    """
    if not doc_path.exists():
        raise FileNotFoundError(f"Contract file not found at: {doc_path}")

    content = doc_path.read_text(encoding="utf-8")
    match = re.search(
        r"## 2\. Path Drift Guard List.*?```text\r?\n(.*?)\r?\n```",
        content,
        re.DOTALL,
    )
    if not match:
        raise ValueError(
            f"Could not find '## 2. Path Drift Guard List' fenced block in {doc_path}"
        )

    paths = [line.strip() for line in match.group(1).strip().splitlines() if line.strip()]
    return paths


def parse_contract_endpoints(doc_path: Path = CONTRACT_FILE) -> dict[str, set[str]]:
    """
    Parses documented HTTP methods and paths from Section 5 of docs/api-contract.md.
    Matches headings of format: '#### `<METHOD> <PATH>`'.
    Strips query parameters (e.g., '?status=...') to extract the canonical base route.
    Returns a dictionary mapping path string to a set of HTTP method strings.
    """
    if not doc_path.exists():
        raise FileNotFoundError(f"Contract file not found at: {doc_path}")

    content = doc_path.read_text(encoding="utf-8")
    # Matches '#### `METHOD /path`' or '#### `METHOD /path?query...`'
    pattern = r"####\s+`([A-Z]+)\s+([^`\s?]+)(?:\?[^`]*)?`"
    matches = re.findall(pattern, content)
    if not matches:
        raise ValueError(f"No endpoint definitions found in {doc_path}")

    endpoints: dict[str, set[str]] = {}
    for method, path in matches:
        endpoints.setdefault(path, set()).add(method.upper())
    return endpoints


def get_registered_app_routes(application: FastAPI) -> dict[str, set[str]]:
    """
    Extracts application routes from FastAPI application instance.
    - Excludes FastAPI built-in documentation routes (/docs, /redoc, /openapi.json, etc.).
    - Excludes automatic HEAD and OPTIONS methods generated by FastAPI for GET endpoints.
    Returns mapping of path string to a set of HTTP method strings.
    """
    app_routes: dict[str, set[str]] = {}
    for route in application.routes:
        path = getattr(route, "path", None)
        if path in FASTAPI_BUILTIN_PATHS:
            continue
        if isinstance(route, APIRoute):
            # Exclude automatic HEAD/OPTIONS added by FastAPI
            methods = {m for m in route.methods if m not in {"HEAD", "OPTIONS"}}
            if methods:
                app_routes.setdefault(route.path, set()).update(methods)
        elif type(route).__name__ == "_IncludedRouter":
            sub_routes = getattr(route.original_router, "routes", [])
            for sub_route in sub_routes:
                if isinstance(sub_route, APIRoute):
                    methods = {m for m in sub_route.methods if m not in {"HEAD", "OPTIONS"}}
                    if methods:
                        app_routes.setdefault(sub_route.path, set()).update(methods)
    return app_routes


class RouteDiff:
    """Computes differences between documented contract and registered application routes."""

    def __init__(
        self,
        guard_paths: list[str],
        contract_endpoints: dict[str, set[str]],
        app_routes: dict[str, set[str]],
    ):
        self.guard_paths = guard_paths
        self.contract_endpoints = contract_endpoints
        self.app_routes = app_routes

        self.expected_pairs: set[tuple[str, str]] = {
            (method, path)
            for path, methods in contract_endpoints.items()
            for method in methods
        }
        self.registered_pairs: set[tuple[str, str]] = {
            (method, path)
            for path, methods in app_routes.items()
            for method in methods
        }

        self.matched: set[tuple[str, str]] = self.registered_pairs & self.expected_pairs
        self.missing: set[tuple[str, str]] = self.expected_pairs - self.registered_pairs
        self.unexpected: set[tuple[str, str]] = self.registered_pairs - self.expected_pairs

        self.expected_paths: set[str] = set(guard_paths)
        self.registered_paths: set[str] = set(app_routes.keys())
        self.missing_paths: set[str] = self.expected_paths - self.registered_paths
        self.unexpected_paths: set[str] = self.registered_paths - self.expected_paths


def get_route_contract_diff(application: FastAPI = app) -> RouteDiff:
    guard_paths = parse_contract_guard_paths()
    contract_endpoints = parse_contract_endpoints()
    app_routes = get_registered_app_routes(application)
    return RouteDiff(guard_paths, contract_endpoints, app_routes)


