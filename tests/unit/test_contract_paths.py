def test_contract_documentation_integrity():
    """
    Verifies that docs/api-contract.md is internally consistent:
    1. Section 2 Path Drift Guard List contains exactly 13 paths (12 contract + /health).
    2. Section 5 Endpoints Specification defines method/path pairs for all 13 paths.
    3. No undocumented paths or internal drift exist within the contract specification itself.
    """
    guard_paths = parse_contract_guard_paths()
    endpoints = parse_contract_endpoints()

    # Must contain exactly 13 paths
    assert len(guard_paths) == 13, f"Expected 13 paths in §2 guard list, found {len(guard_paths)}"
    assert len(endpoints) == 13, f"Expected 13 endpoints in §5 specifications, found {len(endpoints)}"

    # Paths in §2 and §5 must match 1-to-1
    assert set(guard_paths) == set(endpoints.keys()), (
        f"Discrepancy between §2 guard paths and §5 endpoint specs:\n"
        f"In §2 but not §5: {set(guard_paths) - set(endpoints.keys())}\n"
        f"In §5 but not §2: {set(endpoints.keys()) - set(guard_paths)}"
    )

    # Verify key contract paths are present
    expected_sample_paths = {
        "/auth/login",
        "/resources",
        "/access-requests",
        "/access-requests/me",
        "/access-requests/{id}/pin",
        "/admin/access-requests",
        "/admin/access-requests/{id}/approve",
        "/admin/access-requests/{id}/reject",
        "/admin/credentials/{id}/revoke",
        "/admin/logs",
        "/admin/nodes",
        "/device/v1/sync",
        "/health",
    }
    assert set(guard_paths) == expected_sample_paths


def test_fastapi_builtin_routes_excluded():
    """
    Verifies that FastAPI built-in documentation routes (/docs, /redoc, /openapi.json)
    are present on the app instance but properly isolated so they do not cause false failures.
    """
    all_route_paths = {getattr(r, "path", None) for r in app.routes if getattr(r, "path", None)}
    assert "/docs" in all_route_paths
    assert "/openapi.json" in all_route_paths

    app_routes = get_registered_app_routes(app)
    for builtin in FASTAPI_BUILTIN_PATHS:
        assert builtin not in app_routes, f"Built-in route {builtin} was not excluded from application routes"


def test_no_unexpected_application_routes():
    """
    Verifies that no unregistered or undocumented routes exist in the FastAPI application.
    Any application route added without being in docs/api-contract.md fails this test.
    """
    diff = get_route_contract_diff(app)
    assert not diff.unexpected, (
        f"Unexpected application routes found that are not in docs/api-contract.md:\n"
        + "\n".join(f"  + {m} {p}" for m, p in sorted(diff.unexpected))
    )


def test_registered_routes_match_contract_spec():
    """
    Verifies that every currently registered application route matches the contract's
    documented HTTP method and path.
    """
    diff = get_route_contract_diff(app)
    for method, path in diff.registered_pairs:
        assert path in diff.contract_endpoints, f"Path {path} not in contract"
        assert method in diff.contract_endpoints[path], (
            f"Method {method} for path {path} does not match documented contract methods "
            f"{diff.contract_endpoints[path]}"
        )


def test_operational_health_route_registered():
    """
    Verifies that the operational health probe GET /health (docs/api-contract.md §5.5)
    is registered on the application with method GET.
    """
    app_routes = get_registered_app_routes(app)
    assert "/health" in app_routes, "Operational route /health is not registered"
    assert "GET" in app_routes["/health"], "Route /health does not support GET method"


def test_contract_drift_report_and_gap_detection():
    """
    Tests the drift detection mechanism and verifies the integrated application baseline:
    - Exactly 13 routes are registered (1 health + 12 contract routes).
    - 0 contract routes are missing.
    - 0 unexpected routes are present.
    """
    diff = get_route_contract_diff(app)

    expected_all_registered = {
        ("GET", "/health"),
        ("POST", "/auth/login"),
        ("GET", "/resources"),
        ("POST", "/access-requests"),
        ("GET", "/access-requests/me"),
        ("GET", "/access-requests/{id}/pin"),
        ("GET", "/admin/access-requests"),
        ("POST", "/admin/access-requests/{id}/approve"),
        ("POST", "/admin/access-requests/{id}/reject"),
        ("POST", "/admin/credentials/{id}/revoke"),
        ("GET", "/admin/logs"),
        ("GET", "/admin/nodes"),
        ("POST", "/device/v1/sync"),
    }
    assert diff.matched == expected_all_registered, (
        f"Registered routes mismatch:\n"
        f"Missing from registered: {expected_all_registered - diff.matched}\n"
        f"Unexpected in registered: {diff.matched - expected_all_registered}"
    )

    assert diff.missing == set(), f"Missing routes mismatch: {diff.missing}"
    assert len(diff.unexpected) == 0


def test_all_contract_routes_registered():
    """
    Authoritative path drift guard test (docs/api-contract.md §2).
    Compares all 13 documented contract endpoints against FastAPI registered routes.
    All 13 routes from Person A and Person B are now registered.
    """
    diff = get_route_contract_diff(app)
    assert not diff.missing, (
        f"Contract drift detected: {len(diff.missing)} of {len(diff.expected_pairs)} "
        f"documented contract routes are not registered on the application:\n"
        + "\n".join(f"  - {m} {p}" for m, p in sorted(diff.missing))
    )
