"""
tests/integration/test_postgres_boundaries.py -- PostgreSQL compatibility and runtime boundaries.

Separates and distinguishes behaviors tested on SQLite from those requiring PostgreSQL:
  1. PostgreSQL DDL compilation tests (offline, runnable in SQLite test suite):
     - Partial unique index: uq_credentials_resource_active (Rule R1: status = 'active').
     - Identity columns (GENERATED BY DEFAULT AS IDENTITY).
     - Interval check constraint: end_at - start_at <= INTERVAL '24 hours'.
     - Trigger definition: trg_credentials_terminal_immutability.
     - Stored procedure definition: next_change_seq().

  2. PostgreSQL live connection tests (skipped when Neon / live PG is not connected):
     - Executing next_change_seq() PL/pgSQL function.
     - Testing row locking (SELECT ... FOR UPDATE) and concurrent lock contention.
     - Testing partial unique index enforcement at the DB engine level.
     - Testing terminal immutability trigger preventing reversion from 'consumed'/'revoked'.
"""
