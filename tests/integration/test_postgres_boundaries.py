# ---------------------------------------------------------------------------
# 1. PostgreSQL Schema & DDL Compilation Tests (Always Runs)
# ---------------------------------------------------------------------------

class TestPostgresDdlCompilation:
    """Verifies that all SQLAlchemy models generate valid PostgreSQL DDL constructs."""

    def test_identity_column_compilation(self):
        """Primary keys must compile to BIGINT GENERATED BY DEFAULT AS IDENTITY."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["access_requests"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY" in ddl
        assert "PRIMARY KEY (id)" in ddl

    def test_interval_check_constraint_compilation(self):
        """AccessRequest window must compile with PostgreSQL INTERVAL '24 hours' check constraint."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["access_requests"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "INTERVAL '24 hours'" in ddl
        assert "ck_access_requests_max_24h" in ddl

    def test_timestamptz_compilation(self):
        """All datetime columns must compile to TIMESTAMP WITH TIME ZONE."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["credentials"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "valid_from TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
        assert "valid_until TIMESTAMP WITH TIME ZONE NOT NULL" in ddl

    def test_access_events_check_constraints_compilation(self):
        """AccessEvent table compiles valid PostgreSQL check constraints for source, types, trust."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["access_events"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "ck_access_events_source" in ddl
        assert "ck_access_events_event_type" in ddl
        assert "ck_access_events_device_time_trusted" in ddl
        assert "source != 'device' OR time_trusted IS NOT NULL" in ddl

    def test_descending_audit_index_compilation(self):
        """AccessEvent audit log index compiles with occurred_at DESC."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["access_events"]
        idx = next(i for i in table.indexes if i.name == "ix_access_events_occurred_at_desc")
        ddl = str(CreateIndex(idx).compile(dialect=pg_dialect))

        assert "CREATE INDEX ix_access_events_occurred_at_desc" in ddl
        assert "occurred_at DESC" in ddl

    def test_credentials_revoke_reason_check_compilation(self):
        """Credential table compiles check constraint enforcing status and revoke_reason pairing."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["credentials"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "ck_credentials_revoke_reason" in ddl
        assert "status = 'revoked' AND revoke_reason IS NOT NULL AND revoke_reason IN ('admin', 'superseded')" in ddl
        assert "status != 'revoked' AND revoke_reason IS NULL" in ddl

    def test_sync_state_singleton_constraint_compilation(self):
        """SyncState table compiles check constraint enforcing id = 1."""
        pg_dialect = postgresql.dialect()
        table = Base.metadata.tables["sync_state"]
        ddl = str(CreateTable(table).compile(dialect=pg_dialect))

        assert "ck_sync_state_single_row" in ddl
        assert "id = 1" in ddl


